// Generates the README parameter table from src/params.js (defaults, ranges) and
// src/param-docs.js (descriptions), so the docs can't drift from the code.
// Usage: node scripts/params-table.mjs           rewrite the table in README.md
//        node scripts/params-table.mjs --check   exit 1 if README.md is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { SCHEMA } from '../src/params.js';
import { PARAM_DOCS } from '../src/param-docs.js';

const README = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../README.md');
const START = '<!-- params:start (generated by scripts/params-table.mjs; do not edit) -->';
const END = '<!-- params:end -->';

const kebab = (k) => k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
const code = (v) => '`' + (typeof v === 'string' ? `'${v}'` : String(v)) + '`';

function range(spec) {
  switch (spec.type) {
    case 'number':
      return `${spec.min} – ${spec.max}`;
    case 'int':
      return `integer, ${spec.min} – ${spec.max}`;
    case 'enum':
      return spec.values.map(code).join(', ');
    case 'seed':
      return `integer, ${spec.min} – ${spec.max}, or \`null\``;
    case 'bool':
      return '`true`, `false`';
    case 'container':
      return 'Element, CSS selector or `null`';
    case 'sprite':
      return "`'auto'`, `'procedural'` or a URL";
  }
  return '';
}

/** The markdown table, one row per option, in schema order. */
export function paramsTable() {
  const rows = Object.entries(SCHEMA).map(([key, spec]) => {
    const attr = spec.type === 'container' ? '—' : `\`data-${kebab(key)}\``;
    return `| \`${key}\` | ${attr} | ${code(spec.default)} | ${range(spec)} | ${PARAM_DOCS[key]} |`;
  });
  return ['| Option | Data attribute | Default | Values | Description |', '|---|---|---|---|---|', ...rows].join('\n');
}

export function updatedReadme(text) {
  const i = text.indexOf(START);
  const j = text.indexOf(END);
  if (i < 0 || j < i) throw new Error('README.md has no params:start / params:end markers');
  return text.slice(0, i + START.length) + '\n' + paramsTable() + '\n' + text.slice(j);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = readFileSync(README, 'utf8');
  const next = updatedReadme(text);
  if (process.argv.includes('--check')) {
    if (next !== text) {
      console.error('README.md parameter table is out of date: run `npm run docs`');
      process.exit(1);
    }
    console.log('README.md parameter table is up to date');
  } else if (next !== text) {
    writeFileSync(README, next);
    console.log('README.md parameter table updated');
  }
}
